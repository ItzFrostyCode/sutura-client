// Writes the SUTURA logo files, the PNG/ICO exports, the in-app markup and a QA sheet. Renderer: librsvg via sharp.
// Usage: node scripts/brand/assets.js <out-dir> [<ts-module-path>]
const fs = require('fs'); const path = require('path');
const sharp = require(process.env.SHARP || 'sharp');
const mark = require('./tapeMark.js');
const word = JSON.parse(fs.readFileSync(path.join(__dirname, 'word.json'), 'utf8'));
const OUT = process.argv[2]; fs.mkdirSync(OUT, { recursive: true });
const { light: LIGHT, dark: DARK, mono: MONO } = mark.PALETTES;
const CREAM = '#FAF6F3';
const detailFor = (px) => (px < 48 ? 'small' : 'full');
const svgOpen = (vb, w, h) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}"${w ? ` width="${f(w)}" height="${f(h)}"` : ''} role="img" aria-label="SUTURA">`;
const f = (n) => Math.round(n * 10) / 10;

// Symbol alone, square box.
const icon = (pal, px, opts = {}) => {
  const detail = opts.detail ?? detailFor(px ?? 512);
  return `${svgOpen(mark.SQUARE, px, px)}${mark(pal, { detail, id: opts.id ?? 'sm', mono: pal === MONO })}</svg>`;
};
// Browser-tab / home-screen tile: the mark on a cream rounded square (reads on light and dark tab bars).
const tile = (px, radius = 112) => {
  const detail = detailFor(px);
  return `${svgOpen('0 0 512 512', px, px)}<rect width="512" height="512" rx="${radius}" fill="${CREAM}"/><svg x="28" y="28" width="456" height="456" viewBox="${mark.SQUARE}">${mark(LIGHT, { detail, id: 'ti' })}</svg></svg>`;
};
// Lockup: symbol (its box scaled to 120 tall), 16 gap, Playfair Display Bold wordmark with the caps centred on the S.
const K = 120 / mark.BOX.h, SYM_W = mark.BOX.w * K, WORD_X = SYM_W + 16 - word.x1;
const BASE = (mark.S_CENTRE_Y - mark.BOX.y) * K + word.capHeight / 2;
const LW = Math.ceil(WORD_X + word.x2 + 2), LH = 120;
const lockup = (pal, h, opts = {}) => {
  const detail = opts.detail ?? detailFor(h ?? 512);
  const wordFill = pal === DARK ? '#F3ECE6' : pal === MONO ? '#000000' : '#4A3428';
  return `${svgOpen(`0 0 ${LW} ${LH}`, h ? (LW / LH) * h : 0, h)}<svg width="${f(SYM_W)}" height="120" viewBox="${mark.BOX.x} ${mark.BOX.y} ${mark.BOX.w} ${mark.BOX.h}">${mark(pal, { detail, id: opts.id ?? 'lk', mono: pal === MONO })}</svg><path fill="${wordFill}" transform="translate(${f(WORD_X)} ${f(BASE)})" d="${word.d}"/></svg>`;
};

const files = {
  'logo.svg': lockup(LIGHT, 0, { detail: 'full' }),
  'logo-on-dark.svg': lockup(DARK, 0, { detail: 'full' }),
  'logo-mono.svg': lockup(MONO, 0, { detail: 'full' }),
  'logo-icon.svg': icon(LIGHT, 0, { detail: 'full' }),
  'favicon.svg': tile(),
};
for (const [n, s] of Object.entries(files)) fs.writeFileSync(path.join(OUT, n), s.replace(/ width="0" height="0"/, '') + '\n');

// In-app markup: light palette, the needle's gap painted in the page colour (no ids, so any number can share a page).
if (process.argv[3]) {
  const halo = { halo: 'var(--sutura-halo, #FAF6F3)' };
  const m = (d) => JSON.stringify(mark(LIGHT, { detail: d, gap: halo }));
  fs.writeFileSync(process.argv[3], `// Generated by scripts/brand/assets.js (tapeMark.js + word.json) — edit those, not this file.
// SUTURA "S-Tape & Needle" symbol as SVG markup (inner content of an <svg>): the same drawing at two weights —
// full (48px and up) and small (under 48px: heavier lines, no ticks / rivet holes / twist strip).
export const MARK_VIEWBOX = ${JSON.stringify(mark.SQUARE)};
export const MARK_FULL = ${m('full')};
export const MARK_SMALL = ${m('small')};
/** The lockup: the symbol's own box, drawn ${f(SYM_W)} wide x 120 tall, then the wordmark. */
export const LOCKUP = { width: ${LW}, height: ${LH}, symbolWidth: ${f(SYM_W)}, box: ${JSON.stringify(mark.BOX)}, wordX: ${f(WORD_X)}, baseline: ${f(BASE)} };
/** "SUTURA" in Playfair Display Bold (OFL), tracked +0.03em, outlined; baseline at y=0, font size 100. */
export const WORDMARK = ${JSON.stringify(word.d)};
/** Box of the outlined wordmark alone. */
export const WORDMARK_VIEWBOX = '${Math.floor(word.x1)} ${Math.floor(word.y1)} ${Math.ceil(word.x2 - word.x1) + 1} ${Math.ceil(word.y2 - word.y1) + 1}';
`);
}

const png = (svg) => sharp(Buffer.from(svg), { density: 72 }).png({ compressionLevel: 9 }).toBuffer();
const up = async (b, k) => { const m = await sharp(b).metadata(); return sharp(b).resize(m.width * k, m.height * k, { kernel: 'nearest' }).png().toBuffer(); };

(async () => {
  // Apple home-screen icon: opaque square (iOS rounds the corners); full detail reads at 180px.
  fs.writeFileSync(path.join(OUT, 'apple-touch-icon.png'), await png(`${svgOpen('0 0 512 512', 180, 180)}<rect width="512" height="512" fill="${CREAM}"/><svg x="24" y="24" width="464" height="464" viewBox="${mark.SQUARE}">${mark(LIGHT, { detail: 'full', id: 'ap' })}</svg></svg>`));
  const frames = await Promise.all([16, 32, 48].map((s) => png(tile(s))));
  const header = Buffer.alloc(6); header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(frames.length, 4);
  let offset = 6 + 16 * frames.length; const dir = [];
  frames.forEach((b, i) => { const s = [16, 32, 48][i]; const e = Buffer.alloc(16); e.writeUInt8(s, 0); e.writeUInt8(s, 1); e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6); e.writeUInt32LE(b.length, 8); e.writeUInt32LE(offset, 12); offset += b.length; dir.push(e); });
  fs.writeFileSync(path.join(OUT, 'favicon.ico'), Buffer.concat([header, ...dir, ...frames]));

  const W = 1500; const layers = []; let labels = ''; let y = 20;
  const row = async (title, bg, ink, items) => {
    const h = 40 + Math.max(...items.map((i) => i.h)) + 40;
    layers.push({ input: { create: { width: W, height: h, channels: 4, background: bg } }, top: y, left: 0 });
    labels += `<text x="24" y="${y + 26}" font-family="Helvetica" font-size="16" font-weight="700" fill="${ink}">${title}</text>`;
    let x = 24;
    for (const it of items) { layers.push({ input: it.b, top: y + 40, left: x }); labels += `<text x="${x}" y="${y + 40 + it.h + 18}" font-family="Helvetica" font-size="12" fill="${ink}">${it.cap}</text>`; x += it.w + 34; }
    y += h + 8;
  };
  const item = async (svg, s, cap, wide = false) => { let b = await png(svg); const m = await sharp(b).metadata(); const k = !wide && s <= 48 ? 3 : 1; if (k > 1) b = await up(b, k); return { b, w: m.width * k, h: m.height * k, cap: `${cap}${k > 1 ? ' (3×)' : ''}` }; };
  const sizes = [16, 24, 32, 48, 128];
  await row('logo-icon on light — one drawing: small weight under 48px, full from 48px', '#FAF6F3', '#2D2A26', await Promise.all(sizes.map((s) => item(icon(LIGHT, s, { id: `a${s}` }), s, `${s}px ${detailFor(s)}`))));
  await row('logo-icon on dark (#231B16)', '#231B16', '#EFE6DE', await Promise.all(sizes.map((s) => item(icon(DARK, s, { id: `b${s}` }), s, `${s}px`))));
  await row('logo-icon mono on white', '#FFFFFF', '#000000', await Promise.all(sizes.map((s) => item(icon(MONO, s, { id: `c${s}` }), s, `${s}px`))));
  await row('favicon tile — light and dark tab bars', '#E9E6E2', '#2D2A26', await Promise.all([16, 24, 32, 48].map((s) => item(tile(s), s, `${s}px`))));
  await row('favicon tile — dark tab bar', '#2B2B2E', '#EEEEEE', await Promise.all([16, 24, 32, 48].map((s) => item(tile(s), s, `${s}px`))));
  await row('lockup — header sizes, 1×', '#FAF6F3', '#2D2A26', await Promise.all([26, 32, 48, 96].map((h) => item(lockup(LIGHT, h, { id: `l${h}` }), h, `${h}px tall (${detailFor(h)})`, true))));
  await row('logo-on-dark.svg and logo-mono.svg, 1×', '#231B16', '#EFE6DE', [await item(lockup(DARK, 96, { id: 'd96' }), 96, 'on dark 96px', true)]);
  await row('logo-mono.svg on white, and the 512px icon', '#FFFFFF', '#000000', [await item(lockup(MONO, 96, { id: 'm96' }), 96, 'mono 96px', true), await item(icon(LIGHT, 512, { id: 'big' }), 512, '512px', true)]);
  await row('apple-touch-icon.png (180×180, 1×)', '#FAF6F3', '#2D2A26', [{ b: fs.readFileSync(path.join(OUT, 'apple-touch-icon.png')), w: 180, h: 180, cap: '180px' }]);
  layers.push({ input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${y}">${labels}</svg>`), top: 0, left: 0 });
  await sharp({ create: { width: W, height: y, channels: 4, background: '#FFFFFF' } }).composite(layers).png().toFile(path.join(OUT, 'qa-sheet.png'));
  console.log('done', Object.keys(files).join(' '), '+ apple-touch-icon.png favicon.ico qa-sheet.png');
})().catch((e) => { console.error(e); process.exit(1); });
